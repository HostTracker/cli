// Command gen reads the published HostTracker OpenAPI document and emits
// one cobra command per operation, grouped by tag, into cmd/gen.
//
//	go run ./internal/gen -spec openapi-3.0.json -out cmd/gen
//
// The emitted files are committed: building the CLI must not need the
// document, and a reviewer sees exactly which commands a spec change
// added, renamed or removed.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	spec := flag.String("spec", "openapi-3.0.json", "path to the OpenAPI document")
	out := flag.String("out", filepath.Join("cmd", "gen"), "directory the generated files are written to")
	pkg := flag.String("package", "gen", "package name of the generated files")
	flag.Parse()

	doc, err := load(*spec)
	if err != nil {
		return err
	}
	groups, err := build(doc)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		return err
	}
	if err := clean(*out); err != nil {
		return err
	}

	doc0, err := emitDoc(*pkg, groups, doc.Info.Title, doc.Info.Version)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(*out, "doc.go"), doc0, 0o644); err != nil {
		return err
	}

	commands := 0
	for _, g := range groups {
		source, err := emit(*pkg, g)
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(*out, fileName(g.Name)), source, 0o644); err != nil {
			return err
		}
		commands += len(g.Commands)
	}

	names := make([]string, 0, len(groups))
	for _, g := range groups {
		names = append(names, fmt.Sprintf("%s (%d)", g.Name, len(g.Commands)))
	}
	sort.Strings(names)
	fmt.Printf("generated %d commands in %d groups: %s\n", commands, len(groups), strings.Join(names, ", "))
	return nil
}

// clean removes the previously generated files, so a renamed group does
// not leave a stale one behind.
func clean(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		raw, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(raw), "// Code generated by internal/gen") {
			continue
		}
		if err := os.Remove(path); err != nil {
			return err
		}
	}
	return nil
}
